  /// Retourne les arrêts atteignables en bus direct depuis [fromName].
  /// Tri : compatibles en premier, puis le reste.
  static List<String> getCompatibleArrivals(String fromName) {
    final fromNorm = fromName.toLowerCase().trim();
    final compatible = <String>{};
    const lineDirs = [
      ('01', 0), ('01', 1),
      ('08', 0), ('08', 1),
      ('10', 0), ('10', 1),
    ];
    for (final (route, dir) in lineDirs) {
      final stops = getStops(route, dir);
      final fromIdx = stops.indexWhere(
          (s) => s.name.toLowerCase().contains(fromNorm));
      if (fromIdx == -1) continue;
      for (int i = fromIdx + 1; i < stops.length; i++) {
        compatible.add(stops[i].name);
      }
    }
    final all = getAllPlannerStopNames();
    final compatList = (compatible.toList()..sort());
    final rest = all.where((s) => !compatible.contains(s) && s != fromName).toList();
    return [...compatList, ...rest];
  }

  /// Tous les noms d'arrêts uniques pour l'autocomplétion du planificateur.
  static List<String> getAllPlannerStopNames() {
    final seen = <String>{};
    final result = <String>[];
    for (final stops in [
      stopsL01dir0, stopsL01dir1,
      stopsL08dir0, stopsL08dir1,
      stopsL10dir0, stopsL10dir1,
      stopsL112dir0, stopsL112dir1,
      stopsL163dir0, stopsL163dir1,
      stopsL172dir0, stopsL172dir1,
    ]) {
      for (final s in stops) {
        if (seen.add(s.name)) result.add(s.name);
      }
    }
    result.sort();
    return result;
  }

  /// Calcule les prochains trajets directs de [fromName] à [toName].
  static List<TripResult> planTrip(String fromName, String toName) {
    final nowParis = DateTime.now(); // heure locale directe (pas de conversion UTC)

    final results = <TripResult>[];
    const lineDirs = [
      ('01', 0), ('01', 1),
      ('08', 0), ('08', 1),
      ('10', 0), ('10', 1),
    ];

    for (final (route, dir) in lineDirs) {
      final stops = getStops(route, dir);
      final fromNorm = fromName.toLowerCase().trim();
      final toNorm = toName.toLowerCase().trim();

      // Cherche le premier fromStop et le dernier toStop
      int fromIdx = -1, toIdx = -1;
      for (int i = 0; i < stops.length; i++) {
        if (fromIdx == -1 && stops[i].name.toLowerCase().contains(fromNorm)) fromIdx = i;
      }
      for (int i = stops.length - 1; i >= 0; i--) {
        if (toIdx == -1 && stops[i].name.toLowerCase().contains(toNorm)) toIdx = i;
      }
      if (fromIdx == -1 || toIdx == -1 || fromIdx >= toIdx) continue;

      final config = lignesConfig.firstWhere(
        (l) => l['num'] == route,
        orElse: () => {'num': route, 'label': 'L$route',
            'color': const Color(0xFF484F54), 'aller': '→', 'retour': '←'},
      );
      final terminus = (dir == 0 ? config['aller'] : config['retour']) as String;

      final dirStr = dir.toString();
      var fromTimes = _resolveTimes(route, dirStr, stops[fromIdx].id);
      if (fromTimes.isEmpty) continue;
      fromTimes = List<String>.from(fromTimes)..sort();

      int found = 0;
      for (final depStr in fromTimes) {
        if (found >= 4) break;
        final depDt = _parseStopTime(depStr, nowParis);
        final waitMin = depDt.difference(nowParis).inMinutes;
        if (waitMin < -1) continue;

        // Heure d'arrivée au stop destination
        final stopsAway = toIdx - fromIdx;
        final arrDt = _findNextTime(route, dirStr, stops[toIdx].id, depDt, stopsAway, nowParis);
        if (arrDt == null) continue;
        final duration = arrDt.difference(depDt).inMinutes;
        if (duration < 0 || duration > 120) continue;

        // Séquence complète des arrêts avec horaires
        final stopTimes = <StopTime>[];
        for (int i = fromIdx; i <= toIdx; i++) {
          final dist = i - fromIdx;
          final t = dist == 0
              ? depDt
              : _findNextTime(route, dirStr, stops[i].id, depDt, dist, nowParis);
          final hhmm = t != null
              ? '${t.hour.toString().padLeft(2, '0')}:${t.minute.toString().padLeft(2, '0')}'
              : '·';
          stopTimes.add(StopTime(stopName: stops[i].name, time: hhmm));
        }

        results.add(TripResult(
          lineNum: route,
          lineColor: config['color'] as Color,
          lineLabel: config['label'] as String,
          terminus: terminus,
          departureTime: depStr,
          arrivalTime: '${arrDt.hour.toString().padLeft(2, '0')}:${arrDt.minute.toString().padLeft(2, '0')}',
          durationMin: duration,
          waitMinutes: max(0, waitMin),
          stops: stopTimes,
        ));
        found++;
      }
    }

    results.sort((a, b) => a.departureTime.compareTo(b.departureTime));
    return results.take(8).toList();
  }

  // Résout les horaires d'un arrêt (GTFS direct ou interpolé).
  static List<String> _resolveTimes(String route, String dir, String stopId) {
    final key = '${route}_${dir}_$stopId';
    final direct = _horairesGTFS[key];
    if (direct != null && direct.isNotEmpty) return direct;
    final interp = _interpolatedStops[key];
    if (interp != null) {
      return _addMinutes(_horairesGTFS[interp.$1] ?? [], interp.$2);
    }
    return [];
  }

  static DateTime _parseStopTime(String hhmm, DateTime base) {
    final p = hhmm.split(':');
    return DateTime(base.year, base.month, base.day,
        int.parse(p[0]), int.parse(p[1]));
  }

  // Premier horaire à stopId tel que: heure >= depDt + minStopsAway minutes.
  static DateTime? _findNextTime(String route, String dir, String stopId,
      DateTime depDt, int minStopsAway, DateTime base) {
    var times = _resolveTimes(route, dir, stopId);
    if (times.isEmpty) return null;
    times = List<String>.from(times)..sort();
    final minExpected = depDt.add(Duration(minutes: max(0, minStopsAway)));
    for (final t in times) {
      final dt = _parseStopTime(t, base);
      if (!dt.isBefore(minExpected)) return dt;
    }
    return null;
  }

