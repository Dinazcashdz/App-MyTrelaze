  static List<String> _addMinutes(List<String> times, int offset) {
    return times.map((heure) {
      final p = heure.split(':');
      var total = int.parse(p[0]) * 60 + int.parse(p[1]) + offset;
      if (total < 0) total += 24 * 60;
      return '${(total ~/ 60).toString().padLeft(2, '0')}:${(total % 60).toString().padLeft(2, '0')}';
    }).toList();
  }

  // ── Calcule le décalage UTC pour Europe/Paris (CET/CEST) ─────────────────
  static int parisOffsetHours(DateTime utc) => _parisOffsetHours(utc);
  static int _parisOffsetHours(DateTime utc) {
    final m = utc.month;
    if (m > 3 && m < 10) return 2;   // Avril–Septembre : toujours CEST
    if (m < 3 || m > 10) return 1;   // Nov–Fév : toujours CET
    // Mars ou Octobre : vérifier le dernier dimanche
    DateTime lastSundayOf(int month) {
      var d = DateTime.utc(utc.year, month + 1, 0);
      while (d.weekday != DateTime.sunday) { d = d.subtract(const Duration(days: 1)); }
      return d;
    }
    if (m == 3) {
      // Passage à l'heure d'été : dernier dimanche de mars à 1h UTC
      final ts = lastSundayOf(3);
      return utc.isAfter(DateTime.utc(utc.year, 3, ts.day, 1)) ? 2 : 1;
    } else {
      // Passage à l'heure d'hiver : dernier dimanche d'octobre à 1h UTC
      final ts = lastSundayOf(10);
      return utc.isAfter(DateTime.utc(utc.year, 10, ts.day, 1)) ? 1 : 2;
    }
  }

  static Future<List<Map<String, dynamic>>> getPassagesByStopAndRoute(
      String stopId, String routeDir) async {
    final parts = routeDir.split('_');
    final route = parts[0];
    final dir = parts[1];

    // Essaie d'abord les données temps réel
    try {
      final rt = await _fetchRealTime(stopId, route, dir);
      if (rt.isNotEmpty) return rt;
    } catch (_) {}

    // Repli sur les horaires GTFS statiques
    return _getStaticPassages(stopId, route, dir);
  }

  // ── Données temps réel via data.angers.fr ────────────────────────────────
  static Future<List<Map<String, dynamic>>> _fetchRealTime(
      String stopId, String route, String dir) async {
    final config = lignesConfig.firstWhere(
      (l) => l['num'] == route,
      orElse: () => {'num': route, 'label': 'Ligne $route', 'color': const Color(0xFF484F54), 'aller': '→', 'retour': '←'},
    );
    final destination = dir == '0' ? (config['aller'] as String) : (config['retour'] as String);

    // L'API utilise le numéro sans zéro initial : "01" → "1", "08" → "8"
    final lineNum = int.tryParse(route)?.toString() ?? route;

    // mnemoarret correspond à nos stopId internes
    final where = 'mnemoarret="$stopId" AND mnemoligne="$lineNum"';
    final uri = Uri.parse(
      'https://data.angers.fr/api/explore/v2.1/catalog/datasets'
      '/bus-tram-circulation-passages/records'
      '?where=${Uri.encodeComponent(where)}'
      '&order_by=depart'
      '&limit=6',
    );

    final response = await http.get(uri).timeout(const Duration(seconds: 5));
    if (response.statusCode != 200) return [];

    final data = jsonDecode(response.body) as Map<String, dynamic>;
    final results = (data['results'] as List?) ?? [];
    if (results.isEmpty) return [];

    final nowUtc = DateTime.now().toUtc();
    final parisOffset = Duration(hours: _parisOffsetHours(nowUtc));
    final nowParis = nowUtc.add(parisOffset);

    final passages = <Map<String, dynamic>>[];
    for (final r in results) {
      // Préférer l'heure temps réel (depart), sinon théorique
      final departStr = (r['depart'] ?? r['departtheorique']) as String?;
      if (departStr == null) continue;
      final depart = DateTime.tryParse(departStr);
      if (depart == null) continue;

      final departParis = depart.toUtc().add(parisOffset);
      final diff = departParis.difference(nowParis).inMinutes;
      if (diff < -1) continue;

      final hh = departParis.hour.toString().padLeft(2, '0');
      final mm = departParis.minute.toString().padLeft(2, '0');
      final isRealtime = (r['fiable'] as String?) == 'F';

      passages.add({
        'ligne': route,
        'destination': (r['dest'] as String?) ?? destination,
        'heure': '$hh:$mm',
        'minutesRestantes': diff < 0 ? 0 : diff,
        'color': config['color'],
        'theorique': !isRealtime,
      });
      if (passages.length >= 6) break;
    }
    return passages;
  }

  // ── Horaires GTFS statiques (repli) ──────────────────────────────────────
  static List<Map<String, dynamic>> _getStaticPassages(
      String stopId, String route, String dir) {
    final key = '${route}_${dir}_$stopId';
    List<String> horaires = _horairesGTFS[key] ?? [];

    if (horaires.isEmpty) {
      final interp = _interpolatedStops[key];
      if (interp != null) {
        final baseTimes = _horairesGTFS[interp.$1] ?? [];
        horaires = _addMinutes(baseTimes, interp.$2);
      }
    }

    final config = lignesConfig.firstWhere(
      (l) => l['num'] == route,
      orElse: () => {'num': route, 'label': 'Ligne $route', 'color': const Color(0xFF484F54), 'aller': '→', 'retour': '←'},
    );
    final destination = dir == '0' ? (config['aller'] as String) : (config['retour'] as String);

    // Utiliser l'heure locale directement — l'app cible des utilisateurs français
    // dont l'appareil est configuré en heure Paris. La conversion UTC→Paris
    // cause un +2h erroné sur les émulateurs qui signalent UTC mais affichent l'heure locale.
    final now = DateTime.now();

    final List<({DateTime dt, String heure})> all = [];
    for (final heure in horaires) {
      final p = heure.split(':');
      final h = int.parse(p[0]);
      final m = int.parse(p[1]);
      if (h >= 24) continue;
      final dt = DateTime(now.year, now.month, now.day, h, m);
      all.add((dt: dt, heure: heure));
    }
    all.sort((a, b) => a.dt.compareTo(b.dt));

    final passages = <Map<String, dynamic>>[];
    for (final entry in all) {
      final diff = entry.dt.difference(now).inMinutes;
      if (diff >= -1) {
        passages.add({
          'ligne': route,
          'destination': destination,
          'heure': entry.heure,
          'minutesRestantes': diff < 0 ? 0 : diff,
          'color': config['color'],
          'theorique': true,
        });
        if (passages.length >= 6) break;
      }
    }
    return passages;
  }

  // Retourne les prochains départs (synchrone) pour un stop key GTFS
  static List<DateTime> getNextDepartures(String stopKey, DateTime from, {int count = 3}) {
    final horaires = _horairesGTFS[stopKey] ?? [];
    final result = <DateTime>[];
    for (final t in horaires) {
      final p = t.split(':');
      final h = int.parse(p[0]);
      final m = int.parse(p[1]);
      if (h >= 24) continue;
      final dt = DateTime(from.year, from.month, from.day, h, m);
      if (!dt.isBefore(from)) {
        result.add(dt);
        if (result.length >= count) break;
      }
    }
    return result;
  }

